/**
 * Версия установленного приложения. Берётся из истории изменений, а не из конфига: на вебе
 * конфиг в сборку не попадает, а равенство первой записи и `expo.version` в app.json проверяет тест,
 * который запускается перед каждой сборкой.
 */
export const APP_VERSION: string = CHANGELOG[0].version;

/** Сравнение версий вида 1.16.5: отрицательное, если a старше b; ноль, если равны. */
export function compareVersions(a: string, b: string): number {
  const pa = a.split('.').map((x) => parseInt(x, 10) || 0);
  const pb = b.split('.').map((x) => parseInt(x, 10) || 0);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (d) return d;
  }
  return 0;
}

/**
 * Что показать после обновления до `current`, если в прошлый раз пользователь видел `lastSeen`:
 * все записи новее `lastSeen` и не новее `current`. Если `lastSeen` неизвестен (приложение
 * обновилось с версии, где этого экрана ещё не было) — только запись текущей версии.
 */
export function unseenReleases(current: string, lastSeen: string | null | undefined, log: Release[] = CHANGELOG): Release[] {
  if (!lastSeen) return log.filter((r) => compareVersions(r.version, current) === 0);
  return log.filter((r) => compareVersions(r.version, lastSeen) > 0 && compareVersions(r.version, current) <= 0);
}
